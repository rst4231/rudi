function reserveDailyQuestion(history=[],date=''){
 const recent=new Set(history.slice(0,4).map(row=>String(row.theme||'').toLocaleLowerCase('ru-RU')));
 const offset=Math.abs(Math.floor(Date.parse(date+'T12:00:00Z')/86400000)||0)%QUESTIONS.length;
 for(const avoidRecent of [true,false])for(let i=0;i<QUESTIONS.length;i++){
  const [theme,question]=QUESTIONS[(offset+i)%QUESTIONS.length];
  if(avoidRecent&&recent.has(theme.toLocaleLowerCase('ru-RU')))continue;
  if(history.some(row=>similarQuestion(question,row.question)))continue;
  return {question,theme,model:'reserve-v1',provider:'local'};
 }
 throw Error('daily-question-reserve-exhausted');
}
