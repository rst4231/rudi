'use strict';

// Choose a small, deterministic theme icon when the title contains no emoji.
// It is applied before creating the TickTick task, so saved titles stay consistent.
const EMOJI_IN_TITLE=/[\p{Extended_Pictographic}\p{Regional_Indicator}\u20e3]/u;
const TASK_ICON_RULES=[
  [/лулу|собак|песик|пёс|щен|питомец|ветеринар/u,'🐕'],
  [/мусор|выбросить|выкинуть|отход|утилиз/u,'🗑️'],
  [/продукт|закуп|магазин|супермаркет|купить|купи|покупк|маркет|доставк|заказ продуктов/u,'🛒'],
  [/завтрак|обед|ужин|готов(ить|ка|ить)|кухн|рецепт|печь|испечь/u,'🍳'],
  [/посуда|тарелк|посудомой/u,'🍽️'],
  [/стирк|стират|бель[её]|прачеч/u,'🧺'],
  [/уборк|убрать|уберись|пылесос|помыть пол|вымыть пол|протереть пыль|чистк/u,'🧹'],
  [/ремонт|почин|прикрут|собрат|инструмент|полк|розетк/u,'🛠️'],
  [/оплат|квитанц|коммунал|сч[её]т|плат[её]ж|банков|налог/u,'💳'],
  [/работ|проект|отч[её]т|созвон|совещан|встреча по работе/u,'💻'],
  [/доктор|врач|больниц|анализ|медицин|стоматолог|аптек/u,'🩺'],
  [/тренир|спорт|зарядк|фитнес|зал|бег|бассейн|йог/u,'🏃'],
  [/машин|авто|заправ|шиномонтаж|мойка авто|техосмотр/u,'🚗'],
  [/поезд|отпуск|путешеств|билет|собрать чемодан|аэропорт/u,'🧳'],
  [/кино|фильм|сериал|театр|концерт/u,'🎬'],
  [/ресторан|кафе|свидани|романтич|ужин вдвоем|ужин вдвоём/u,'❤️'],
  [/подар|сюрприз|день рожден/u,'🎁'],
  [/цветы|букет|растен|полить/u,'🌷'],
  [/гуля|прогулк|парк|пройтись/u,'🚶'],
  [/учить|урок|экзамен|образован|обучен|книг|читать|прочитать/u,'📚'],
  [/позвон|звонок|созвониться|перезвон/u,'📞'],
  [/план|список|написать|записать|документ|оформить/u,'📝'],
];
function withTaskEmoji(title){
  const value=String(title||'').trim();
  if(!value||EMOJI_IN_TITLE.test(value))return value;
  const normalized=value.toLocaleLowerCase('ru-RU');
  const match=TASK_ICON_RULES.find(([pattern])=>pattern.test(normalized));
  return (match?.[1]||'📌')+' '+value;
}
module.exports={withTaskEmoji};
