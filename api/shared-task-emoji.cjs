'use strict';
function decorateSharedTaskTitle(input){
 const title=String(input||'').trim();
 if(!title)return '';
 if(/^(?:\p{Extended_Pictographic}|[0-9#*]\uFE0F?\u20E3)/u.test(title))return title;
 const name=title.toLocaleLowerCase('ru-RU').replace(/ё/g,'е');
 const rules=[
  [/лулу|собак|питомц|ветеринар|выгулять|выгул/,'🐶'],
  [/убор|прибра|пылесос|вымыть пол|помыть пол|протереть пыль/,'🧹'],
  [/посуд|тарелк|чашк|бокал/,'🍽️'],
  [/стирк|белье|постира|прачечн/,'🧺'],
  [/продукт|покупк|купить|магазин|супермаркет|доставк/,'🛒'],
  [/готов|приготов|ужин|обед|завтрак|рецепт/,'🍳'],
  [/прогул|погуля|пройтись|гулять/,'🚶'],
  [/кино|фильм|сериал|театр|концерт/,'🎬'],
  [/свидан|ресторан|кафе|встреча/,'❤️'],
  [/трениров|фитнес|спорт|зал|бег/,'💪'],
  [/машин|авто|шины|колес|заправ|мойк/,'🚗'],
  [/оплат|платеж|счет|коммунал|аренд|банк|финанс/,'💳'],
  [/врач|клиник|анализ|лекарств|аптек|стоматолог/,'🏥'],
  [/путешеств|поездк|отпуск|билет|вокзал|аэропорт/,'✈️'],
  [/ремонт|почин|собрат|повесит|прибит|инструмент/,'🛠️'],
  [/сад|растени|цветы|полить/,'🪴'],
  [/звон|позвон|написат|сообщени/,'📞'],
  [/документ|паспорт|справк|регистрац|загс/,'📄'],
  [/купат|душ|ванн|туалет|санузел/,'🛁'],
 ];
 const found=rules.find(([re])=>re.test(name));
 return (found?found[1]:'📌')+' '+title;
}
module.exports={decorateSharedTaskTitle};
